// switch case

let condition = 4;

switch (condition){

    case 1:
        console.log("O caso 1 é: ",condition);
        break;

    case 2:
        console.log("O caso 2 é: ",condition);
        break;

    case 3:
        console.log("O caso 3 é: ",condition);
        break;

    default:
        console.log("O caso default é: false");

}